package main

import (
	"bytes"
	"testing"
)

func TestFixedStatementAndWitnessExport(t *testing.T) {
	var generated bytes.Buffer
	if err := exportPairings(&generated, "v6.1.0"); err != nil {
		t.Fatal(err)
	}
	want, err := files.ReadFile("testdata/sp1-v6.1.0-pairing.json")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(want, generated.Bytes()) {
		t.Fatal("export differs from the compact frontend's pinned coordinates")
	}
}
